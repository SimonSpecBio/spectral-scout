const VALID_CODES = new Set<string>(US_STATES.map((s) => s.code));

export function isValidStateCode(code: string): boolean {
  return VALID_CODES.has(code.toUpperCase());
}

export function stateName(code: string): string | undefined {
  return US_STATES.find((s) => s.code === code.toUpperCase())?.name;
}
